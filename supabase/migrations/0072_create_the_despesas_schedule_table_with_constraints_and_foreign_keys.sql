CREATE TABLE public.programacoes_saidas (
  id text NOT NULL,
  descricao text NOT NULL,
  frequencia text NOT NULL,
  dia_vencimento integer NOT NULL,
  data_inicio date NOT NULL,
  repeticoes integer,
  valor_previsto numeric(14,2),
  categoria_id text NOT NULL,
  banco_id text NOT NULL,
  participante_tipo text,
  pessoa_id text,
  empresa_id text,
  fornecedor_id text,
  participante_nome text,
  participante_documento text,
  observacoes text NOT NULL DEFAULT '',
  ativa boolean NOT NULL DEFAULT true,
  created_by text,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  updated_at timestamp with time zone NOT NULL DEFAULT now(),
  CONSTRAINT programacoes_saidas_pkey PRIMARY KEY (id),
  CONSTRAINT programacoes_saidas_frequencia_check CHECK (frequencia IN ('MENSAL_CONTINUA', 'AVULSA', 'REPETICAO_FINITA')),
  CONSTRAINT programacoes_saidas_dia_check CHECK (dia_vencimento >= 1 AND dia_vencimento <= 31),
  CONSTRAINT programacoes_saidas_repeticoes_check CHECK ((frequencia = 'REPETICAO_FINITA' AND repeticoes IS NOT NULL AND repeticoes >= 1) OR (frequencia <> 'REPETICAO_FINITA' AND repeticoes IS NULL)),
  CONSTRAINT programacoes_saidas_valor_check CHECK (valor_previsto IS NULL OR valor_previsto > 0),
  CONSTRAINT programacoes_saidas_participante_tipo_check CHECK (participante_tipo IS NULL OR participante_tipo IN ('FORNECEDOR', 'INSTRUTOR', 'COORDENADOR', 'EMPRESA', 'ALUNO')),
  CONSTRAINT programacoes_saidas_participante_check CHECK ((participante_tipo IS NULL AND pessoa_id IS NULL AND empresa_id IS NULL AND fornecedor_id IS NULL) OR (participante_tipo IN ('INSTRUTOR', 'COORDENADOR', 'ALUNO') AND pessoa_id IS NOT NULL AND empresa_id IS NULL AND fornecedor_id IS NULL) OR (participante_tipo = 'EMPRESA' AND empresa_id IS NOT NULL AND pessoa_id IS NULL AND fornecedor_id IS NULL) OR (participante_tipo = 'FORNECEDOR' AND fornecedor_id IS NOT NULL AND pessoa_id IS NULL AND empresa_id IS NULL)),
  CONSTRAINT programacoes_saidas_categoria_id_fkey FOREIGN KEY (categoria_id) REFERENCES public.categorias_financeiras(id) ON DELETE RESTRICT,
  CONSTRAINT programacoes_saidas_banco_id_fkey FOREIGN KEY (banco_id) REFERENCES public.bancos(id) ON DELETE RESTRICT,
  CONSTRAINT programacoes_saidas_pessoa_id_fkey FOREIGN KEY (pessoa_id) REFERENCES public.pessoas(id) ON DELETE RESTRICT,
  CONSTRAINT programacoes_saidas_empresa_id_fkey FOREIGN KEY (empresa_id) REFERENCES public.empresas(id) ON DELETE RESTRICT,
  CONSTRAINT programacoes_saidas_fornecedor_id_fkey FOREIGN KEY (fornecedor_id) REFERENCES public.fornecedores(id) ON DELETE RESTRICT
)
CREATE TABLE public.vendas (
  id text NOT NULL,
  participante_tipo text NOT NULL,
  pessoa_id text,
  empresa_id text,
  participante_nome text NOT NULL,
  participante_documento text,
  curso_id text,
  turma_id text,
  condicao text NOT NULL,
  parcelas_quantidade integer NOT NULL DEFAULT 1,
  categoria_id text NOT NULL,
  banco_id text NOT NULL,
  forma_pagamento text,
  referencia_transacao text,
  cartao_ultimos_digitos text,
  observacoes text NOT NULL DEFAULT '',
  created_by text,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  updated_at timestamp with time zone NOT NULL DEFAULT now(),
  CONSTRAINT vendas_pkey PRIMARY KEY (id),
  CONSTRAINT vendas_participante_tipo_check CHECK (participante_tipo IN ('ALUNO', 'EMPRESA')),
  CONSTRAINT vendas_participante_check CHECK ((participante_tipo = 'ALUNO' AND pessoa_id IS NOT NULL AND empresa_id IS NULL) OR (participante_tipo = 'EMPRESA' AND empresa_id IS NOT NULL AND pessoa_id IS NULL)),
  CONSTRAINT vendas_condicao_check CHECK (condicao IN ('A_VISTA', 'PARCELADO')),
  CONSTRAINT vendas_parcelas_quantidade_check CHECK (parcelas_quantidade >= 1 AND parcelas_quantidade <= 120),
  CONSTRAINT vendas_forma_pagamento_check CHECK (forma_pagamento IS NULL OR forma_pagamento IN ('PIX', 'DINHEIRO', 'BOLETO', 'TRANSFERENCIA', 'CARTAO', 'CHEQUE', 'OUTRO')),
  CONSTRAINT vendas_cartao_digitos_check CHECK (cartao_ultimos_digitos IS NULL OR cartao_ultimos_digitos ~ '^[0-9]{4}$'),
  CONSTRAINT vendas_pessoa_id_fkey FOREIGN KEY (pessoa_id) REFERENCES public.pessoas(id) ON DELETE RESTRICT,
  CONSTRAINT vendas_empresa_id_fkey FOREIGN KEY (empresa_id) REFERENCES public.empresas(id) ON DELETE RESTRICT,
  CONSTRAINT vendas_curso_id_fkey FOREIGN KEY (curso_id) REFERENCES public.cursos(id) ON DELETE RESTRICT,
  CONSTRAINT vendas_turma_id_fkey FOREIGN KEY (turma_id) REFERENCES public.turmas(id) ON DELETE SET NULL,
  CONSTRAINT vendas_categoria_id_fkey FOREIGN KEY (categoria_id) REFERENCES public.categorias_financeiras(id) ON DELETE RESTRICT,
  CONSTRAINT vendas_banco_id_fkey FOREIGN KEY (banco_id) REFERENCES public.bancos(id) ON DELETE RESTRICT
)